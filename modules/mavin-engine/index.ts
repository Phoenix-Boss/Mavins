/**
 * Resolve a URL to its content type, canonical ID, and service.
 *
 * Deep linking pattern:
 *   const resolved = await resolveUrl(sharedUrl);
 *   if (resolved.type === 'stream')   → getStreamInfo(resolved.url)
 *   if (resolved.type === 'channel')  → getChannelInfo(resolved.url)
 *   if (resolved.type === 'playlist') → getPlaylistInfo(resolved.url)
 *
 * Throws if the URL cannot be handled or the link type cannot be determined.
 * getLinkTypeByUrl() exceptions are caught and re-thrown with a clear message.
 * Null channel/playlist factories (services that don't support them) are
 * also caught and re-thrown with a descriptive error.
 */
export const resolveUrl = (
  url: string,
  serviceId?: number
): Promise<ResolvedUrl> =>
  Native.resolveUrl(url, serviceId ?? null);

/**
 * Check whether any registered service can handle a URL.
 * Never throws — returns canHandle: false on errors.
 *
 * Both the serviceId and no-serviceId paths return the same shape,
 * including linkType. serviceName is always present.
 */
export const canHandleUrl = (
  url: string,
  serviceId?: number
): Promise<CanHandleResult> =>
  Native.canHandleUrl(url, serviceId ?? null);

/**
 * Extract just the canonical content ID from a URL.
 * Lighter-weight than resolveUrl when you only need the ID.
 * Throws on unhandled URLs or null factories.
 */
export const extractIdFromUrl = (
  url: string,
  serviceId?: number
): Promise<ExtractedId> =>
  Native.extractIdFromUrl(url, serviceId ?? null);

