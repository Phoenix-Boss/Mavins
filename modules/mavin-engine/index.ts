// ─────────────────────────────────────────────
// Shared sub-types
// ─────────────────────────────────────────────

export interface NativeImage {
  url: string;
  width: number;
  height: number;
  resolutionLevel: 'UNKNOWN' | 'LOW' | 'MEDIUM' | 'HIGH' | 'VERY_HIGH';
}

/**
 * Pagination cursor returned by the Kotlin layer.
 * When there is no next page, this is an empty object `{}`.
 * Always use `hasNextPage` to check for more pages.
 * 
 * Kotlin Page class uses getters: getUrl(), getIds(), getCookies()
 * but expo-modules-core converts these to plain object fields.
 */
export interface NativePage {
  url: string;
  ids: string[];
  cookies: Record<string, string>;
}

