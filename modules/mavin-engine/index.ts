/**
 * Search for content across a service.
 *
 * filter defaults to "all" (YoutubeSearchQueryHandlerFactory.ALL).
 * Valid YouTube filters: "all" | "videos" | "channels" | "playlists" |
 * "music_songs" | "music_videos" | "music_albums" | "music_playlists"
 *
 * Passing null or undefined for filter also resolves to "all" in the
 * Kotlin layer via the YoutubeSearchQueryHandlerFactory.ALL default.
 */
/**
 * Search for content on a service.
 *
 * filter: leave blank ('') for all content types. Per NewPipe API docs,
 *   an empty contentFilter list means no filter. The string 'all' is NOT
 *   a valid NewPipe filter — always use '' for unfiltered results.
 *
 * Valid YouTube filters: 'videos' | 'channels' | 'playlists' |
 *   'music_songs' | 'music_videos' | 'music_albums' | 'music_playlists'
 *
 * serviceId: omit or pass undefined for YouTube (0 = default).
 *   Kotlin receives null and applies NewPipe.getService(0).
 */
export const search = (
  query: string,
  filter: SearchFilter = '',
  pageUrl?: string,
  serviceId?: number
): Promise<SearchPage | SearchMorePage> => {
  if (!query?.trim()) {
    return Promise.reject(new Error('Search query cannot be empty'));
  }
  // Pass filter as-is. '' means no filter (all results) per NewPipe API.
  // Pass null for serviceId when not specified — Kotlin defaults to YouTube (0).
  return Native.search(query.trim(), filter, pageUrl ?? null, serviceId ?? null);
};

