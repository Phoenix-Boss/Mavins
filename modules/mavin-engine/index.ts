/**
 * MavinEngine Native Module Wrapper
 *
 * Single source of truth JS/TS bridge.
 * Every function maps 1-to-1 to an AsyncFunction in MavinEngineModule.kt.
 *
 * Kotlin module name:  "MavinEngine"
 * Extractor version:   NewPipeExtractor 0.26.0
 *
 * Service IDs (NewPipe standard):
 *   0 = YouTube
 *   1 = SoundCloud
 *   2 = MediaCCC
 *   3 = PeerTube
 *   4 = Bandcamp
 */

import { requireNativeModule } from 'expo-modules-core';

// ─────────────────────────────────────────────
// Native Module
// ─────────────────────────────────────────────

const Native = requireNativeModule('MavinEngine');

if (!Native) {
  console.error('[MavinEngine] CRITICAL: native module not loaded.');
}

// ─────────────────────────────────────────────
// Shared sub-types
// ─────────────────────────────────────────────

export interface NativeImage {
  url: string;
  width: number;
  height: number;
  resolutionLevel: 'UNKNOWN' | 'LOW' | 'MEDIUM' | 'HIGH' | 'VERY_HIGH';
}

/**
 * Pagination cursor returned by the Kotlin layer.
 * NOTE: In 0.26.x the Kotlin side always returns a non-null map for nextPage
 * (an empty map `{}` when there is no next page).  Use `hasNextPage` to gate
 * pagination logic rather than null-checking this object.
 */
export interface NativePage {
  url: string;
  ids: string[];
  cookies: Record<string, string>;
}

