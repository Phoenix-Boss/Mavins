export const search = (
  query: string,
  filter: SearchFilter = 'all',
  pageUrl?: string,
  serviceId?: number
): Promise<SearchPage | SearchMorePage> => {
  if (!query?.trim()) throw new Error('Search query cannot be empty');
  return Native.search(query.trim(), filter, pageUrl ?? null, serviceId ?? null);
};

