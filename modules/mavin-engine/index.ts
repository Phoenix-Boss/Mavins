/**
 * Search across a service.
 * filter: service-specific string e.g. 'all', 'videos', 'channels', 'playlists'
 * For pagination pass nextPage.url as pageUrl.
 * Defaults to YouTube (serviceId=0).
 */
export const search = async (
  query: string,
  filter: SearchFilter = 'all',
  pageUrl?: string,
  serviceId?: number
): Promise<SearchPage | SearchMorePage> => {
  if (!query?.trim()) throw new Error('Search query cannot be empty');
  return Native.search(query.trim(), filter, pageUrl ?? null, serviceId ?? null);
};

/**
 * Autocomplete suggestions for a partial query.
 */
export const getSearchSuggestions = async (
  query: string,
  serviceId?: number
): Promise<string[]> => {
  return Native.getSearchSuggestions(query, serviceId ?? null);
};

/**
 * Returns the available content filter strings for a service.
 * Use these as the filter argument in search().
 */
export const getSearchFilters = async (
  serviceId?: number
): Promise<SearchFiltersResult> => {
  return Native.getSearchFilters(serviceId ?? null);
};

