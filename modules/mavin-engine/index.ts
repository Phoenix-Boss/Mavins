/**
 * All possible source strings from getTrendingWithFallback().
 *
 * Layer 1: "youtube_music_charts"         — FEmusic_charts InnerTube API
 * Layer 2: "innertube_browse"             — FEwhat_to_watch homepage feed
 * Layer 3: "kiosk_{id}"                  — e.g. "kiosk_trending_music"
 * Layer 4: "youtube_charts_html"          — charts.youtube.com HTML scrape
 * Layer 5: "innertube_next_recommendations" — Next API recommendations seed
 * Layer 6: "search_{year}"               — e.g. "search_2026"
 * Cache:   "cache"                        — in-memory 5-minute cache hit
 * Failure: "none"                         — all 6 layers failed
 */
export type TrendingSource =
  | 'youtube_music_charts'
  | 'innertube_browse'
  | `kiosk_${string}`
  | 'youtube_charts_html'
  | 'innertube_next_recommendations'
  | `search_${number}`
  | 'cache'
  | 'none';

export interface TrendingResult {
  success: boolean;
  /** Which layer provided the data */
  source: TrendingSource;
  /** Up to MAX_TRENDING_ITEMS (6) items */
  items: InfoItem[];
  /** Total items available before the 6-item cap */
  totalAvailable: number;
  /** Error messages from all failed layers */
  errors: string[];
  /** Present only when success is false */
  message?: string;
}

