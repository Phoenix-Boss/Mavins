export const search = (
  query: string,
  filter: string = 'all',
  pageUrl?: string,
  serviceId?: number
): Promise<SearchPage | SearchMorePage> => {
  if (!query?.trim()) {
    return Promise.reject(new Error('Search query cannot be empty'));
  }
  return Native.search(query.trim(), filter, pageUrl ?? null, serviceId ?? null);
};

