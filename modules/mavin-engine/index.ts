/**
 * Get YouTube kiosk by type.
 * 
 * UPDATED for NewPipeExtractor v0.26.0:
 * - Uses lowercase underscore IDs: 'trending_music', 'trending_movies_and_shows', 'live', etc.
 * - Supports both friendly names ('Trending Music') and actual IDs ('trending_music')
 * - Only 'trending_music' and 'trending_movies_and_shows' are working in v0.26.0
 * - 'Trending', 'live', 'trending_gaming', 'trending_podcasts_episodes' are broken (null pointer exceptions)
 * 
 * @param kioskType - Kiosk type or ID (case-insensitive, spaces/underscores/hyphens normalized)
 * @param serviceId - Service ID (default: 0 for YouTube)
 */
export const getYouTubeKiosk = (
  kioskType: 
    | 'LIVE' 
    | 'MUSIC' 
    | 'GAMING' 
    | 'MOVIES' 
    | 'TRENDING'
    | 'trending_music'
    | 'trending_movies_and_shows'
    | 'trending_gaming'
    | 'trending_podcasts_episodes'
    | 'live'
    | 'Trending',
  serviceId: number = 0
): Promise<KioskPage> =>
  Native.getYouTubeKiosk(kioskType, serviceId);

