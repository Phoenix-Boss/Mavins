/**
 * Perform a search
 * @param query - Search query (required, non-empty)
 * @param filter - Search filter (default 'all')
 * @param pageUrl - Optional page URL for pagination
 * @param serviceId - Optional service ID
 */
export const search = (
  query: string,
  filter: string = 'all',
  pageUrl?: string,
  serviceId?: number
): Promise<SearchPage | SearchMorePage> => {
  if (!query?.trim()) {
    return Promise.reject(new Error('Search query cannot be empty'));
  }
  return Native.search(query.trim(), filter, pageUrl ?? null, serviceId ?? null);
};

