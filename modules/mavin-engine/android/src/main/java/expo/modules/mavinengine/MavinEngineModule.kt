/**
 * MavinEngine — NewPipe Extractor v0.26.0 Integration
 * All API calls verified against official Javadoc:
 * https://teamnewpipe.github.io/NewPipeExtractor/javadoc/
 *
 * Key v0.26.0 facts applied:
 *  - Service.getMediaCapabilities() returns Set<MediaCapability> (not List)
 *  - AudioStream.getBitrate() and VideoStream.getBitrate() are the correct methods
 *    (getAverageBitrate() was removed in v0.22.0)
 *  - AudioStream: getAudioTrackId(), getAudioTrackName(), getAudioLocale(), getAudioTrackType()
 *  - VideoStream: getWidth(), getHeight(), getFps(), getBitrate(), getQuality()
 *  - SubtitlesStream: getLanguageTag(), isAutoGenerated, displayLanguageName
 *  - StreamInfo fields accessed via getter methods (not direct field access)
 *  - Description.getContent() (not .content)
 *  - Page: getUrl(), getIds(), getCookies(), getBody() are the correct getter methods
 *  - StreamInfo.getContentAvailability() returns ContentAvailability enum
 *  - CommentsInfoItem.getReplies() returns a Page? (nullable)
 *  - StreamInfo.getInfo(StreamExtractor) calls fetchPage() internally — no pre-fetch needed
 *  - FeedInfo has no pagination (no getMoreItems) in v0.26.0
 *  - ChannelTabInfo.getInfo(service, ListLinkHandler) — takes ListLinkHandler, not String
 *  - KioskInfo.getInfo(service, url) and getMoreItems(service, url, Page) — url is a String
 */
