    // ── Search ──────────────────────────────────────────────────────────────

    /**
     * SearchInfo.getInfo(StreamingService, SearchQueryHandler) — correct signature.
     * SearchInfo.getMoreItems(StreamingService, SearchQueryHandler, Page) — correct signature.
     * service.searchQHFactory.fromQuery(query, contentFilter, sortFilter) — correct.
     * service.searchQHFactory.availableContentFilter — returns array of filter strings.
     */
    @Throws(ExtractionException::class, IOException::class)
    private fun performSearch(
        query: String,
        filter: String,
        pageUrl: String?,
        serviceId: Int?
    ): Map<String, Any> {
        val service = if (serviceId != null) getService(serviceId) else getDefaultService()
        val handler = service.searchQHFactory.fromQuery(query, listOf(filter), "")
