     *  - commentId                                   → getCommentId()
     *  - commentText                                 → getCommentText() returns Description
     *  - textualUploadDate                           → getTextualUploadDate()
     *  - uploadDate                                  → getUploadDate() returns DateWrapper?
     *  - likeCount                                   → getLikeCount() returns int
     *  - textualLikeCount                            → getTextualLikeCount()
     *  - replyCount                                  → getReplyCount() returns int
     *  - getReplies()                                → returns Page? (nullable)
     *  - isPinned                                    → isPinned() getter
     *  - isHeartedByUploader                         → isHeartedByUploader() getter
