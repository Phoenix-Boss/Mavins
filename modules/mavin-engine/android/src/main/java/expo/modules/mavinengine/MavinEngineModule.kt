    // ── Downloader ──────────────────────────────────────────────────────────

    /**
     * Downloader.execute(Request) — the single method to implement.
     * Request methods: url(), httpMethod(), headers(), dataToSend().
     * Response constructor: Response(int responseCode, String responseMessage,
     *   Map<String,List<String>> headers, @Nullable String responseBody,
     *   @Nullable String latestUrl)
     */
    class MavinDownloader(private val client: OkHttpClient) : Downloader() {
        @Throws(IOException::class, ExtractionException::class)
        override fun execute(request: org.schabi.newpipe.extractor.downloader.Request): Response {
            val builder = Request.Builder().url(request.url())
            when (request.httpMethod()) {
                "POST" -> {
                    val body = request.dataToSend()
                    builder.post(
                        if (body != null)
                            RequestBody.create(
                                "application/x-www-form-urlencoded".toMediaTypeOrNull(),
                                body
                            )
                        else
                            RequestBody.create(null, ByteArray(0))
                    )
                }
                "HEAD" -> builder.head()
                else   -> builder.get()
            }
            val headers = request.headers()
            if (!headers.containsKey("User-Agent")) {
                builder.addHeader(
                    "User-Agent",
                    "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
                        "(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
                )
            }
            headers.forEach { (key, values) ->
                values.forEach { value -> builder.addHeader(key, value) }
            }
            val okResponse = client.newCall(builder.build()).execute()
            val responseBody = okResponse.body?.string() ?: ""
            val responseHeaders = okResponse.headers.toMultimap()
            return Response(
                okResponse.code,
                okResponse.message,
                responseHeaders,
                responseBody,
                okResponse.request.url.toString()
            )
        }
    }
