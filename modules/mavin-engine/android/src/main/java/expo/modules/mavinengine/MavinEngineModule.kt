    // ── Initialization ──────────────────────────────────────────────────────

    private fun initializeNewPipe() {
        if (isInitialized) return
        synchronized(this) {
            if (isInitialized) return
            try {
                NewPipe.init(
                    MavinDownloader(httpClient),
                    Localization.fromLocale(Locale.US),
                    ContentCountry("US")
                )
                isInitialized = true
                Log.i(TAG, "✅ NewPipe v0.26.0 initialized — ${ServiceList.all().size} services loaded")
            } catch (e: Exception) {
                Log.e(TAG, "NewPipe init failed", e)
                throw CodedException("INIT_FAILED", "NewPipe.init failed: ${e.message}", e)
            }
        }
    }

    private fun ensureInit() {
        if (!isInitialized) initializeNewPipe()
    }

    private fun resetNewPipe(): Map<String, Any> {
        isInitialized = false
        initializeNewPipe()
        return mapOf("success" to true, "message" to "NewPipe reset and re-initialised")
    }

    // ── Service Resolution ──────────────────────────────────────────────────

    private fun getService(serviceId: Int): StreamingService {
        return ServiceList.all().firstOrNull { it.serviceId == serviceId }
            ?: throw ExtractionException("No service with id=$serviceId")
    }

    private fun getDefaultService(): StreamingService {
        return ServiceList.all().firstOrNull { it.serviceId == 0 }
            ?: ServiceList.all().firstOrNull()
            ?: throw ExtractionException("No streaming services registered")
    }

    private fun getServiceForUrl(url: String): StreamingService {
        return ServiceList.all().firstOrNull { service ->
            try {
                service.getLinkTypeByUrl(url) != StreamingService.LinkType.NONE
            } catch (_: Exception) { false }
        } ?: throw ExtractionException("No service can handle URL: $url")
    }

    private fun resolveService(url: String, serviceId: Int?): StreamingService =
        if (serviceId != null) getService(serviceId) else getServiceForUrl(url)

    /**
     * In v0.26.0 getMediaCapabilities() returns Set<MediaCapability>, not List.
     * We call .map { } on it safely since Set is Iterable.
     */
    private fun getServicesList(): List<Map<String, Any>> {
        if (!isInitialized) return emptyList()
        return ServiceList.all().map { s ->
            mapOf<String, Any>(
                "id"                to s.serviceId,
                "name"              to s.serviceInfo.name,
                "baseUrl"           to (s.baseUrl ?: ""),
                // getMediaCapabilities() → Set<MediaCapability> in v0.26.0
                "mediaCapabilities" to s.serviceInfo.mediaCapabilities.map { it.name }
            )
        }
    }

    // ── Stream Extraction ───────────────────────────────────────────────────

    /**
     * StreamInfo.getInfo(StreamExtractor) fetches the page internally.
     * Do NOT call extractor.fetchPage() before it — that would double-fetch.
     * Signature: StreamInfo.getInfo(@Nonnull StreamExtractor extractor)
     */
    @Throws(ExtractionException::class, IOException::class)
    private fun extractStreamInfo(url: String, serviceId: Int?): Map<String, Any> {
        val service = resolveService(url, serviceId)
        val extractor = service.getStreamExtractor(url)
        val info = StreamInfo.getInfo(extractor)          // fetches page internally
        return streamInfoToMap(info, service.serviceId)
    }

    @Throws(ExtractionException::class, IOException::class)
    private fun extractStreamInfoById(videoId: String, serviceId: Int?): Map<String, Any> {
        val service = if (serviceId != null) getService(serviceId) else getDefaultService()
        val linkHandler = service.streamLHFactory.fromId(videoId)
        val extractor = service.getStreamExtractor(linkHandler)
        val info = StreamInfo.getInfo(extractor)          // fetches page internally
        return streamInfoToMap(info, service.serviceId)
    }

    /**
     * StreamInfo field access reference (all are getter methods):
     *  - info.name                → info.getName() in Java; in Kotlin property access is fine
     *  - info.uploaderName        → getter
     *  - info.uploaderUrl         → getter
     *  - info.uploaderAvatars     → getter, returns List<Image>
     *  - info.isUploaderVerified  → isUploaderVerified() getter (boolean)
     *  - info.uploaderSubscriberCount → getter, returns long (-1 if unknown)
     *  - info.duration            → getter, returns long
     *  - info.viewCount           → getter, returns long (-1 if unknown)
     *  - info.likeCount           → getter, returns long (-1 if unknown)
     *  - info.dislikeCount        → getter, returns long (-1 if unknown)
     *  - info.description         → getter, returns Description object
     *  - info.description.content → Description.getContent() in Java → .content in Kotlin
     *  - info.uploadDate          → getter, returns DateWrapper? (nullable)
     *  - info.textualUploadDate   → getter, returns String?
     *  - info.thumbnails          → getter, returns List<Image>
     *  - info.streamType          → getter, returns StreamType enum
     *  - info.isShortFormContent  → isShortFormContent() getter (boolean)
     *  - info.getContentAvailability() → returns ContentAvailability enum
     *  - info.ageLimit            → getter, returns int
     *  - info.tags                → getter, returns List<String>
     *  - info.category            → getter, returns String?
     *  - info.audioStreams        → getter, returns List<AudioStream>
     *  - info.videoStreams        → getter, returns List<VideoStream>
     *  - info.videoOnlyStreams    → getter, returns List<VideoStream>
     *  - info.dashMpdUrl          → getter, returns String
     *  - info.hlsUrl              → getter, returns String
     *  - info.subtitles           → getter, returns List<SubtitlesStream>
     *  - info.relatedItems        → getter, returns List<InfoItem>
     *  - info.metaInfo            → getter, returns List<MetaInfo>
     *
     *  DateWrapper.offsetDateTime() was replaced by .date() returning Instant in v0.25.0+.
     *  Use uploadDate?.date?.toString() safely.
     */
    // Use buildMap to avoid Kotlin type-inference failure on large heterogeneous mapOf blocks
    private fun streamInfoToMap(info: StreamInfo, serviceId: Int): Map<String, Any> =
        buildMap<String, Any> {
            put("success",                 true)
            put("serviceId",               serviceId)
            put("id",                      info.id)
            put("url",                     info.url)
            put("originalUrl",             info.originalUrl)
            put("title",                   info.name.orEmpty())
            put("uploaderName",            info.uploaderName.orEmpty())
            put("uploaderUrl",             info.uploaderUrl.orEmpty())
            put("uploaderAvatars",         info.uploaderAvatars.map { imageToMap(it) })
            put("uploaderVerified",        info.isUploaderVerified)
            // uploaderSubscriberCount returns -1 when unknown; clamp to 0 for JS consumers
            put("uploaderSubscriberCount", info.uploaderSubscriberCount.coerceAtLeast(0))
            put("duration",                info.duration)
            put("viewCount",               info.viewCount.coerceAtLeast(0))
            put("likeCount",               info.likeCount.coerceAtLeast(0))
            put("dislikeCount",            info.dislikeCount.coerceAtLeast(0))
            // Description.content is the plain-text accessor in Kotlin (getContent() in Java)
            put("description",             info.description.content)
            put("uploadDate",              info.uploadDate?.offsetDateTime()?.toString() ?: "")
            put("textualUploadDate",       info.textualUploadDate.orEmpty())
            put("thumbnails",              info.thumbnails.map { imageToMap(it) })
            put("streamType",              info.streamType.name)
            put("isLive",                  info.streamType == LIVE_STREAM || info.streamType == AUDIO_LIVE_STREAM)
            put("isShortFormContent",      info.isShortFormContent)
            // getContentAvailability() returns ContentAvailability enum
            put("availability",            info.getContentAvailability().name)
            put("ageLimit",                info.ageLimit)
            put("tags",                    info.tags)
            put("category",                info.category.orEmpty())
            put("audioStreams",            info.audioStreams.map { audioStreamToMap(it) })
            put("videoStreams",            info.videoStreams.map { videoStreamToMap(it) })
            put("videoOnlyStreams",        info.videoOnlyStreams.map { videoStreamToMap(it) })
            put("dashMpdUrl",              info.dashMpdUrl.orEmpty())
            put("hlsUrl",                  info.hlsUrl.orEmpty())
            put("subtitles",               info.subtitles.map { subtitleToMap(it) })
            put("relatedItems",            info.relatedItems.take(20).mapNotNull { infoItemToMap(it) })
            put("metaInfo",                info.metaInfo.map { m ->
                mapOf<String, Any>(
                    "title"    to m.title.orEmpty(),
                    "content"  to m.content.content,
                    "urls"     to m.urls.map { it.toString() },
                    "urlTexts" to m.urlTexts
                )
            })
        }

    @Throws(ExtractionException::class, IOException::class)
    private fun getBestStreamUrl(url: String, format: String, serviceId: Int?): Map<String, Any> {
        val service = resolveService(url, serviceId)
        val extractor = service.getStreamExtractor(url)
        val info = StreamInfo.getInfo(extractor)
        // AudioStream.getBitrate() and VideoStream.getBitrate() — correct in v0.26.0
        val best = when (format.lowercase()) {
            "audio", "mp3", "m4a", "ogg" ->
                info.audioStreams.maxByOrNull { it.getBitrate() }?.content
            "video", "mp4", "best" ->
                info.videoStreams.maxByOrNull { it.getHeight() }?.content
                    ?: info.videoOnlyStreams.maxByOrNull { it.getHeight() }?.content
            "dash" -> info.dashMpdUrl.takeIf { it.isNotEmpty() }
            "hls"  -> info.hlsUrl.takeIf { it.isNotEmpty() }
            else   -> info.audioStreams.maxByOrNull { it.getBitrate() }?.content
        }
        return mapOf<String, Any>(
            "success"      to (best != null),
            "url"          to (best ?: ""),
            "format"       to format,
            "title"        to info.name.orEmpty(),
            "duration"     to info.duration,
            "fallbackUrls" to listOfNotNull(
                info.dashMpdUrl.takeIf { it.isNotEmpty() },
                info.hlsUrl.takeIf { it.isNotEmpty() }
            )
        )
    }

    @Throws(ExtractionException::class, IOException::class)
